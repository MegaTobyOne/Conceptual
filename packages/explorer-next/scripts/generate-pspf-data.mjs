/**
 * Generates src/pspf/<domain>.ts from @pspf/reference-data (the monorepo's
 * curated PSPF Release 2025 baseline) per ADR 0084 / unification plan Phase B.
 *
 * The reference-data package is the single source of truth for requirement
 * statements; this script only derives presentation fields (app codes,
 * truncated titles) and the Essential Eight association.
 *
 * Run from the package directory after building @pspf/reference-data:
 *   pnpm run generate:pspf-data
 */

import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const packageRoot = resolve(here, '..');
const outDir = resolve(packageRoot, 'src/pspf');

const referenceData = await import(resolve(packageRoot, '../reference-data/dist/index.js'));

/** domainFamily (reference-data) → app domain module metadata. */
const DOMAINS = {
  GOV: {
    key: 'governance',
    name: 'Governance',
    prefix: 'GOV',
    description:
      'Security governance, accountability, and leadership roles including Chief Security Officer (CSO) and Chief Information Security Officer (CISO) appointments.',
  },
  INFO: {
    key: 'information',
    name: 'Information Security',
    prefix: 'INFO',
    description:
      'Protective markings, classifications (OFFICIAL, PROTECTED, SECRET, TOP SECRET), need-to-know principle and secure handling requirements.',
  },
  PER: {
    key: 'personnel',
    name: 'Personnel Security',
    prefix: 'PERS',
    description:
      'Pre-employment screening, security clearance processes, conditional clearance management, and eligibility waiver protocols.',
  },
  PHYS: {
    key: 'physical',
    name: 'Physical Security',
    prefix: 'PHYS',
    description:
      'Security planning for facilities, certification and accreditation of physical assets, access controls, and technical surveillance measures.',
  },
  RISK: {
    key: 'risk',
    name: 'Risk Management',
    prefix: 'RISK',
    description:
      'Security risk management aligned with enterprise risk, including third-party, supply chain, and foreign interference risk management.',
  },
  TECH: {
    key: 'technology',
    name: 'Technology Security',
    prefix: 'TECH',
    description:
      'Cybersecurity strategy with zero trust culture, AI/quantum technology policies, Essential Eight mitigation strategies, and cloud security requirements.',
  },
};

/** PSPF requirement numbers 99–106 are the Essential Eight maturity requirements. */
const E8_BY_REQUIREMENT_NUMBER = {
  99: 'patch-applications',
  100: 'patch-operating-systems',
  101: 'multi-factor-authentication',
  102: 'restrict-administrative-privileges',
  103: 'application-control',
  104: 'restrict-microsoft-office-macros',
  105: 'user-application-hardening',
  106: 'regular-backups',
};

/** PSPF Release 2025 question type → app ReportingType. */
const REPORTING_TYPE_BY_QUESTION_TYPE = {
  Performance: 'maturity',
  'Yes/No': 'binary',
  'Yes/No/NA': 'binary',
};

function deriveTitle(statement) {
  const flat = statement.replace(/\s+/g, ' ').trim();
  if (flat.length <= 96) return flat;
  const cut = flat.slice(0, 78);
  const lastSpace = cut.lastIndexOf(' ');
  return `${cut.slice(0, lastSpace > 40 ? lastSpace : 78).trimEnd()}...`;
}

function ts(value) {
  return JSON.stringify(value);
}

function escapeBackticks(s) {
  return s.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
}

const references = [...referenceData.PSPF_REQUIREMENT_REFERENCES].sort(
  (a, b) => a.requirementNumber - b.requirementNumber,
);

const byFamily = new Map(Object.keys(DOMAINS).map((family) => [family, []]));
for (const reference of references) {
  const bucket = byFamily.get(reference.domainFamily);
  if (!bucket) {
    throw new Error(
      `Unknown domainFamily ${reference.domainFamily} for ${reference.requirementId}`,
    );
  }
  bucket.push(reference);
}

const summary = [];
for (const [family, domain] of Object.entries(DOMAINS)) {
  const rows = byFamily.get(family);
  const lines = [];
  lines.push('// AUTO-GENERATED by scripts/generate-pspf-data.mjs — do not edit by hand.');
  lines.push('// Source of truth: @pspf/reference-data (PSPF Release 2025 baseline).');
  lines.push(`// Attribution: ${rows[0].attribution}. Licence: ${rows[0].licence}.`);
  lines.push('');
  lines.push(`import type { Domain, Requirement } from '../data/types.ts';`);
  lines.push(`import { asRequirementId } from '../data/types.ts';`);
  lines.push('');
  lines.push(`export const ${domain.key}Domain: Domain = {`);
  lines.push(`  key: ${ts(domain.key)},`);
  lines.push(`  name: ${ts(domain.name)},`);
  lines.push(`  description: ${ts(domain.description)},`);
  lines.push(`  prefixes: [${ts(domain.prefix)}],`);
  lines.push(`};`);
  lines.push('');
  lines.push(`export const ${domain.key}Requirements: readonly Requirement[] = [`);
  for (const row of rows) {
    const code = `${domain.prefix}-${String(row.requirementNumber).padStart(3, '0')}`;
    const statement = row.statement.replace(/\s+/g, ' ').trim();
    const e8 = E8_BY_REQUIREMENT_NUMBER[row.requirementNumber];
    const reportingType = REPORTING_TYPE_BY_QUESTION_TYPE[row.questionType] ?? 'unspecified';
    lines.push('  {');
    lines.push(`    id: asRequirementId(${ts(code)}),`);
    lines.push(`    canonicalId: ${ts(row.requirementId)},`);
    lines.push(`    domain: ${ts(domain.key)},`);
    lines.push(`    title: \`${escapeBackticks(deriveTitle(statement))}\`,`);
    lines.push(`    text: \`${escapeBackticks(statement)}\`,`);
    lines.push(`    reportingType: ${ts(reportingType)},`);
    if (e8) lines.push(`    essentialEightControl: ${ts(e8)},`);
    lines.push('  },');
  }
  lines.push('];');
  lines.push('');
  await writeFile(resolve(outDir, `${domain.key}.ts`), lines.join('\n'), 'utf8');
  summary.push(`${domain.key}: ${rows.length}`);
}

console.log(
  `ok generated ${references.length} requirements from @pspf/reference-data (${summary.join(', ')})`,
);
